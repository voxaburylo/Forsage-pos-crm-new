/**
 * 24.11.2026 (власник: «у картці працівника не знайшов жодних налаштувань прав»): блок «Права» в картці.
 * Тут — зрозумілий перелік того, що працівникові дозволяє його роль, і що закрито. Перелік повторює меню
 * програми (Sidebar) і правила каси (desktopAuthorization); сторож — staffRights.test.ts.
 * Те, що власник вмикає окремо, — перемикачі в самому блоці (ManagerSaleToggle.tsx).
 */
export interface RoleRights { can: string[]; cannot: string[] }

const RIGHTS: Record<string, RoleRights> = {
  owner: { can: ['Усе: каса, товари, замовлення, звіти, працівники, налаштування'], cannot: [] },
  admin: { can: ['Усе: каса, товари, замовлення, звіти, працівники, налаштування'], cannot: [] },
  manager: {
    can: ['Товари, прихід, ревізія, постачальники, автозакупівля', 'Клієнти й замовлення, збірка замовлень', 'Аналітика', 'Робота через веб (з телефона чи з дому)'],
    cannot: ['Продаж із каси й зміна — лише з перемикачем нижче', 'Працівники й налаштування'],
  },
  cashier: {
    can: ['Каса: продаж, повернення, зміна, видача готових замовлень', 'Товари, прихід товару, ревізія', 'Клієнти', 'Видача зарплати за день', 'Аналітика'],
    cannot: ['Розділ «Замовлення» (оформлення й ведення замовлень)', 'Постачальники, автозакупівля', 'Працівники й налаштування', 'Робота через веб — лише з перемикачем нижче'],
  },
  storekeeper: {
    can: ['Товари, прихід товару, ревізія', 'Постачальники', 'Збірка замовлень', 'Клієнти'],
    cannot: ['Каса й гроші', 'Замовлення', 'Аналітика', 'Працівники й налаштування'],
  },
  sto_viewer: { can: ['Перегляд товарів і клієнтів', 'Підрахунок у ревізії'], cannot: ['Каса й гроші', 'Зміни в товарах, приході, замовленнях', 'Працівники й налаштування'] },
  tire_worker: { can: [], cannot: ['Входу в програму немає — лише виконавець робіт шиномонтажу'] },
}

export function roleRights(role: string): RoleRights {
  return RIGHTS[role] ?? { can: [], cannot: [] }
}

/** Які перемикачі показує блок «Права» для цієї ролі. */
export function roleSwitches(role: string): Array<'web' | 'sale' | 'deposit'> {
  if (role === 'cashier') return ['web']
  if (role === 'manager') return ['sale', 'deposit']
  return []
}
