// Synthetic shift export through the real background worker and SQLite runtime.
// Never starts the app, sync, network, printer or a working shop database.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { createHash, randomUUID } = require('node:crypto')
const { DatabaseSync } = require('node:sqlite')
const { gunzipSync } = require('node:zlib')
const { pathToFileURL, fileURLToPath } = require('node:url')
const staged = process.argv.includes('--staged')
const compiled = path.resolve(__dirname, staged ? '../release/staged/win-unpacked/resources/app.asar/dist' : '../dist')
const { LocalDatabase } = require(path.join(compiled, 'db/localDatabase.js'))
const { DEFAULT_TENANT_ID } = require(path.join(compiled, 'db/localTypes.js'))
const { LocalCatalogRepository } = require(path.join(compiled, 'repositories/catalogRepository.js'))
const { LocalPosRepository } = require(path.join(compiled, 'repositories/posRepository.js'))
const { ShiftBackupService } = require(path.join(compiled, 'backup/shiftBackupService.js'))
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'forsage-photo-worker-'))
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
let original, restored, service
async function main() {
  try {
    original = new LocalDatabase(root)
    const photo = path.join(root, 'photos', 'source.jpg'), bytes = Buffer.from('synthetic photo fixture')
    fs.mkdirSync(path.dirname(photo))
    fs.writeFileSync(photo, bytes)
    const catalog = new LocalCatalogRepository(original), pos = new LocalPosRepository(original)
    const productId = randomUUID(), invalidId = randomUUID(), cashier = randomUUID()
    catalog.saveProduct({id:productId, sku:'PHOTO-SMOKE', name:'Fixture photo', qty_on_hand:98, photo_url:pathToFileURL(photo).href})
    catalog.saveProduct({id:invalidId, sku:'BAD-URL-SMOKE', name:'Fixture malformed URL', qty_on_hand:3, photo_url:'file:///broken%ZZ.jpg'})
    const timestamp = new Date().toISOString()
    original.prepare('INSERT INTO staff_users(id,tenant_id,full_name,role,created_at,updated_at) VALUES(?,?,?,?,?,?)')
      .run(cashier,DEFAULT_TENANT_ID,'Synthetic cashier','cashier',timestamp,timestamp)
    const shift = pos.openShift({cashier_id:cashier,opening_cash:0})
    pos.closeShift(cashier,0,null,shift)
    const errors = []
    service = new ShiftBackupService(original,path.join(root,'program'),error=>errors.push(String(error.message)))
    await service.tick()
    assert.deepEqual(errors,[])
    const job = original.prepare('SELECT * FROM shift_backups WHERE id=?').get(shift)
    assert.equal(job.local_error,null)
    assert(job.compressed_path && job.sha256)
    assert.equal(hash(fs.readFileSync(job.compressed_path)),job.sha256)
    const decompressed = gunzipSync(fs.readFileSync(job.compressed_path))
    assert.deepEqual(decompressed,fs.readFileSync(job.local_path))
    LocalDatabase.assertBackupIsUsable(job.local_path)
    const probe = new DatabaseSync(job.local_path,{readOnly:true})
    try {
      const coverage = probe.prepare('SELECT COUNT(*) n, SUM(CASE WHEN bytes IS NOT NULL THEN 1 ELSE 0 END) embedded FROM backup_assets').get()
      assert.deepEqual({...coverage},{n:2,embedded:1})
      assert.equal(probe.prepare('SELECT error FROM backup_assets WHERE original_url=?').get('file:///broken%ZZ.jpg').error,'Файл фото відсутній або недоступний')
    } finally { probe.close() }
    assert.equal(service.status(DEFAULT_TENANT_ID)[0].local_ready,true)
    assert.equal(service.status(DEFAULT_TENANT_ID)[0].exports_ready,true)
    await service.stop()
    const target = path.join(root,'restored')
    fs.mkdirSync(path.join(target,'data'),{recursive:true})
    fs.writeFileSync(path.join(target,'data','forsage.db'),decompressed,{flag:'wx'})
    restored = LocalDatabase.open(target).database
    const restoredProduct = restored.prepare('SELECT qty_on_hand,photo_url FROM products WHERE id=?').get(productId)
    assert.equal(restoredProduct.qty_on_hand,98)
    const restoredFile = fileURLToPath(restoredProduct.photo_url)
    assert(restoredFile.startsWith(path.join(target,'photos')+path.sep))
    assert.deepEqual(fs.readFileSync(restoredFile),bytes)
    assert.equal(restored.prepare('SELECT photo_url FROM products WHERE id=?').get(invalidId).photo_url,'file:///broken%ZZ.jpg')
    assert.deepEqual(fs.readFileSync(photo),bytes)
    assert.equal(original.prepare('SELECT qty_on_hand FROM products WHERE id=?').get(productId).qty_on_hand,98)
    assert.equal(original.prepare("SELECT COUNT(*) n FROM sqlite_schema WHERE name='backup_assets'").get().n,0)
    console.log(JSON.stringify({ok:true,stagedModules:staged,backgroundExport:true,gzipExactMatch:true,
      embeddedPhotosRestored:1,invalidPhotosRecorded:1,originalFixtureUnchanged:true,
      shopDatabaseOpened:false,networkRequests:false,printerJobs:false}))
  } finally {
    await service?.stop()
    restored?.close()
    await original?.waitForBackup().catch(()=>{})
    original?.close()
    assert.equal(path.dirname(root),path.resolve(os.tmpdir()))
    assert(path.basename(root).startsWith('forsage-photo-worker-'))
    assert.equal(fs.realpathSync(root),root)
    fs.rmSync(root,{recursive:true,force:true})
  }
}
main().catch(error=>{console.error(error);process.exitCode=1})
