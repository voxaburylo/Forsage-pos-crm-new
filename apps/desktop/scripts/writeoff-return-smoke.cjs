    assert.equal(writeoffCopy.items[0].cost_kopecks,15)
    assert.equal(writeoffCopy.items[0].id,db.prepare('SELECT id FROM writeoff_items WHERE writeoff_id=?').get(written.id).id)
    const outgoing = db.prepare("SELECT * FROM sync_outbox WHERE operation_type='return.created' AND aggregate_id=?").get(first.id)
    const copy = attachBalanceSnapshots(db, [{ ...outgoing, payload: JSON.parse(outgoing.payload_json) }])[0].payload
