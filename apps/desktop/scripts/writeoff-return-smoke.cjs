    assert.equal(row.soldQty, 0)
    assert.equal(row.profit, 0)
    assert.equal(row.abc_class, 'Z')
    const soldFinal = readSoldItems(db,tenant,reportRange.from,reportRange.to)[0]
    assert.equal(soldFinal.qty_net, 0)
    assert.equal(soldFinal.net_revenue, 0)
    const staffFinal = localAnalytics(db, reportRange).find(row => row.manager_id === employee)
    assert.equal(staffFinal.total_revenue, 0)
