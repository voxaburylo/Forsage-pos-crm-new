    const writeoffCopy = attachBalanceSnapshots(db,[{...writeoffRow,payload:JSON.parse(writeoffRow.payload_json)}])[0].payload
    const month = new Intl.DateTimeFormat('sv-SE',{timeZone:'Europe/Kyiv',year:'numeric',month:'2-digit'}).format(new Date())
