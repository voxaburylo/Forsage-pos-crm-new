    assert.equal(invoiceCopy.user_id, cashier)
    assert.equal(invoiceCopy.items[0].total, 15)
    assert.equal(db.prepare('SELECT qty_on_hand FROM products WHERE id=?').get(product).qty_on_hand, 9.7)
    assert.equal(db.prepare('SELECT payload_json FROM sync_outbox WHERE operation_id=?').get(invoiceQueued.operation_id).payload_json, invoiceQueued.payload_json)
    const oldDeletion = { ...deletion, payload: { id: manual.id } }
