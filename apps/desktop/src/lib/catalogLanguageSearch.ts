export function normalizeCatalogLanguage(value: string): string {
  return value.toLocaleLowerCase('uk-UA').replace(/ё/g, 'е').replace(/ґ/g, 'г')
    .replace(/[ії]/g, 'и').replace(/є/g, 'е').replace(/[^a-zа-я0-9]+/gi, ' ').trim()
}
const vocabulary = new Map<string, string[]>()
for (const line of CATALOG_LANGUAGE_GROUPS) {
  const words = [...new Set(normalizeCatalogLanguage(line).split(' '))]
  for (const word of words) vocabulary.set(word, words)
}
export function catalogLanguageTokenGroups(query: string): string[][] {
  return normalizeCatalogLanguage(query).split(/\s+/).filter(Boolean)
    .map(token => vocabulary.get(token) ?? [token])
}
