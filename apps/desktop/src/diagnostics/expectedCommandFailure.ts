/**
 * Звичайна відмова («вкажіть назву», «недостатньо прав», «немає залишку») — не збій програми, а
 * робота перевірок: касир бачить причину на екрані. У журналі проблем має лишатись те, що справді
 * треба чинити. 20.11.2026: журнал набрав 31 запис, з них 606 повторів «Недостатньо залишку» на касі
 * та 101 — сканування в ревізії невідомого штрихкоду.
 */
const EXPECTED_COMMAND_FAILURES = [
  'Недостатньо прав', 'Неприпустиме джерело', 'Сесія', 'вже існує',
  'Вкажіть', 'Введіть', 'Оберіть', 'DESKTOP_SESSION', 'Невірний пароль',
  // Залишок і пошук товару
  'Недостатньо залишку', 'Недостатньо товару', 'INSUFFICIENT_STOCK', 'Товар не знайдено', 'не знайдено в базі',
  // PIN і вхід
  'Невірний PIN', 'Невірний поточний PIN',
  // Правила документів, які програма пояснює на екрані
  'Видалити можна лише', 'має бути більше нуля', 'вже належить іншому', 'уже належить іншому', 'Зарплата стане доступною',
  'Кількість сканування має бути',
]

export function isExpectedCommandFailure(message: string): boolean {
  // «Не пускає провести накладну» повторювалося без сліду: причину рядка пишемо завжди (лише код).
  if (message.includes('RECEIVING_LINE:') || message.includes('RECEIVING_STEP:')) return false
  return EXPECTED_COMMAND_FAILURES.some((marker) => message.includes(marker))
}
