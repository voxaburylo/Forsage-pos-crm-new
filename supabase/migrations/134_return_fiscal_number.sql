-- 134: Фіскальний номер чека повернення (ПРРО Кашалот)
-- Досі номер фіскального чека повернення показувався лише раз на екрані
-- після оформлення і ніде не зберігався — в історії повернень неможливо
-- було довести, яким фіскальним чеком проведено відкат.

ALTER TABLE returns ADD COLUMN IF NOT EXISTS fiscal_number VARCHAR(128);

COMMENT ON COLUMN returns.fiscal_number IS 'Фіскальний номер чека повернення з ПРРО (Кашалот); NULL = нефіскальне повернення';

-- Скидаємо кеш схеми PostgREST, інакше нова колонка "не існує" до рестарту
NOTIFY pgrst, 'reload schema';
