/** Початок назви для правил: нижній регістр, латинська «i» в українських словах → «і», лише перші чотири слова з літерами. */
export function nameHead(name: unknown): string {
  const text = String(name ?? '').toLocaleLowerCase('uk-UA').replace(/[ʼ'`’]/g, '').replace(/(?<=\p{Script=Cyrillic})i|i(?=\p{Script=Cyrillic})/gu, 'і')
  return text.split(/[^\p{L}\-]+/u).filter(word => /\p{Script=Cyrillic}/u.test(word)).slice(0, 4).join(' ')
}

/** Назва категорії, яку підказує правило, або null — алгоритм не певен. */
export function ruleCategoryName(name: unknown): string | null {
  const head = nameHead(name)
  if (!head) return null
  const whole = String(name ?? '').toLocaleLowerCase('uk-UA')
  if (NOT_A_PART.test(whole)) return null
  for (const rule of RULES) {
    if (!rule.head.test(head)) continue
    return rule.not?.test(whole) || (rule.must && !rule.must.test(whole)) ? null : rule.category
  }
  return null
}

/** Назва категорії → її код у магазині. Категорії немає або таких дві — null (правило мовчить). */
export function categoryIndex(options: readonly CategoryOption[]): Map<string, string | null> {
  const index = new Map<string, string | null>()
  for (const option of options) {
    const name = option.path.split(' › ').at(-1)!.trim().toLocaleLowerCase('uk-UA')
    index.set(name, index.has(name) ? null : option.id)
  }
  return index
}

export function ruleCategoryId(name: unknown, index: ReadonlyMap<string, string | null>): string | null {
  const category = ruleCategoryName(name)
  return category ? index.get(category.toLocaleLowerCase('uk-UA')) ?? null : null
}
