/**
 * Розкладка по категоріях БЕЗ штучного інтелекту (26.11.2026, слово власника: «товари зі зрозумілою назвою хай розбирає
 * алгоритм: колодки — у гальмівну систему, сайлентблоки — у підвіску, лампочки — у лампочки; зекономимо кошти, а ШІ
 * лишиться для описів, характеристик, перекладів, створення категорій, пошуку дублів»).
 *
 * Правило дивиться на ПОЧАТОК назви (перші чотири слова): там стоїть вид деталі («Фільтр масляний …», «Гальмівні колодки …»).
 * Слово далі в назві — це вже «для чого» («Підшипник генератора» — підшипник, а не генератор), тому його не чіпаємо.
 * Правила впорядковані від точного до загального; перше, що підійшло, і вирішує. Категорія шукається за точною назвою
 * серед категорій магазину: немає такої (перейменували) чи їх дві — правило мовчить, і товар іде до ШІ, як раніше.
 * Усе, що алгоритм не впізнав напевно, він НЕ вгадує.
 */
