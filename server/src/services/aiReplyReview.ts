import { asksPermissionInText } from './aiPermissionText.js'

/**
 * Запобіжник відповіді помічника: чи треба попросити модель відповісти ще раз. Винесено з aiService.ts 26.11.2026.
 *
 * Що було не так (чат власника 26.11): на запитання «рядок накладної не проводиться — що це означає? Нічого не змінюй сам»
 * помічник відповів порадою («щоб додати…, створіть…»), запобіжник зловив слова «додати/створ» як звіт про виконану дію і
 * змусив відповісти вдруге. Власник отримав лише другу відповідь: «Це було лише запитання, інструмент я не викликав. Моя
 * попередня відповідь була порадою…» — про відповідь, якої він не бачив, і з удвічі довшим очікуванням.
 *
 * Тепер звітом вважається лише дієслово минулого часу про себе («створив», «обʼєднав», «готово»), а не будь-яке слово з
 * коренем «дода/створ»; запитання й прохання «нічого не змінюй» не перевіряються; у вказівці моделі сказано, що власник
 * попередньої відповіді не бачив.
 */
const UNSEEN = ' Власник твою попередню відповідь НЕ бачив: напиши повну відповідь заново й не згадуй ні її, ні це зауваження.'

/** Власник лише питає або прямо просить нічого не змінювати — звіту про дію тут не чекаємо. */
export function ownerOnlyAsks(userText: string): boolean {
  const text = userText.trim()
  return /н[іи]чого\s+не\s+зм[іи]нюй|ничего\s+не\s+меняй|не\s+зм[іи]нюй\s+сам|не\s+меняй\s+сам/iu.test(text)
    || (/\?\s*$/u.test(text) && !/(створи|додай|зміни|обʼєднай|об'єднай|виправ|перейменуй|переклади|создай|добавь|измени|объедини|обьедини|исправь|переименуй|переведи)/iu.test(text))
}

/** Звіт про виконану дію від першої особи: «створив 5 клієнтів», «обʼєднав», «готово». Порада «щоб додати…» — не звіт. */
export function claimsDoneInText(reply: string): boolean {
  return /(?<![\p{L}])(створив|створила|додав|додала|оновив|оновила|видалив|видалила|зав[іе]в|завела|зан[іе]с|занесла|вн[іе]с|внесла|об[ʼ'’`]?єднав|об[ʼ'’`]?єднала|змінив|змінила|виправив|виправила|перейменував|перейменувала|переклав|переклала|зберіг|зберегла|создал|создала|добавил|добавила|обновил|обновила|удалил|удалила|зав[её]л|объединил|исправил|переименовал|перев[её]л|сохранил)(?![\p{L}])/iu.test(reply)
    || /(?<![\p{L}])(готово|виконано|зроблено|сделано|выполнено)(?![\p{L}])/iu.test(reply)
}

export function replyCorrection(input: { reply: string; userText: string; actions: number; preparedJobs: number }): string | null {
  if (!input.reply.trim()) return 'СИСТЕМА: Твоя відповідь була порожньою. Відповідай текстом українською або виклич потрібний інструмент.'
  if (input.actions > 0) return null
  if (asksPermissionInText(input.reply)) {
    return 'СИСТЕМА: Ти питаєш дозволу текстом, але без виклику інструмента власник не бачить жодної кнопки й не може погодитись. Для пунктів, де ти впевнений, виклич інструмент ЗАРАЗ (дублі — merge_products_bulk з причиною до кожної пари й sure=true/false — сумнівні теж туди, з sure=false; назви/категорії — update_products_bulk; кроси — add_cross_numbers_bulk). Кнопка «Підтвердити» під твоєю відповіддю і є згода власника.' + UNSEEN
  }
  if (input.preparedJobs === 0 && !ownerOnlyAsks(input.userText) && claimsDoneInText(input.reply)) {
    return 'СИСТЕМА: Ти відрапортував, ніби виконав дію, але НЕ підготував жодної пропозиції (не викликав інструмент створення/зміни) — у базі НІЧОГО не змінилося. Якщо у повідомленні/файлі є дані для заведення чи зміни — виклич відповідний інструмент ЗАРАЗ: для 2+ записів — масовий, для одного — одиничний. Якщо це було лише запитання — дай відповідь без слів «готово/створив/додав».' + UNSEEN
  }
  return null
}
