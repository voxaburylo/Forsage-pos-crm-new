/** Відповідь просить дозволу текстом («Обʼєднати 18 пар?», «скажете «так»»), хоча пропозиції з кнопкою немає. */
export function asksPermissionInText(reply: string): boolean {
  return /(об[ʼ'’`]?єднати|обьединить|объединить|злити|перейменувати|переименовать|застосувати|додати кроси)[^.?!\n]{0,200}\?/i.test(reply)
    || /скаж(ете|іть|ите)\s+[«"„]?(так|да)(?!\p{L})/iu.test(reply)
}
